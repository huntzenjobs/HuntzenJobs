CREATE OR REPLACE FUNCTION public.claim_email_campaign_deliveries(
  p_campaign_id UUID,
  p_limit INTEGER DEFAULT 100
)
RETURNS TABLE (
  id BIGINT,
  user_id UUID,
  language TEXT,
  batch_number INTEGER
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_batch_number INTEGER;
BEGIN
  IF p_limit < 1 OR p_limit > 100 THEN
    RAISE EXCEPTION 'p_limit must be between 1 and 100';
  END IF;

  PERFORM 1
  FROM public.email_campaigns AS campaign
  WHERE campaign.id = p_campaign_id
    AND campaign.status = 'running'
  FOR UPDATE SKIP LOCKED;

  IF NOT FOUND THEN
    RETURN;
  END IF;

  SELECT MIN(delivery.batch_number)
  INTO v_batch_number
  FROM public.email_campaign_deliveries AS delivery
  WHERE delivery.campaign_id = p_campaign_id
    AND delivery.status = 'pending';

  IF v_batch_number IS NULL THEN
    RETURN;
  END IF;

  RETURN QUERY
  UPDATE public.email_campaign_deliveries AS delivery
  SET
    status = 'sending',
    attempt_count = delivery.attempt_count + 1,
    claimed_at = NOW(),
    updated_at = NOW()
  WHERE delivery.campaign_id = p_campaign_id
    AND delivery.batch_number = v_batch_number
    AND delivery.status = 'pending'
  RETURNING
    delivery.id,
    delivery.user_id,
    delivery.language,
    delivery.batch_number;
END;
$$;

