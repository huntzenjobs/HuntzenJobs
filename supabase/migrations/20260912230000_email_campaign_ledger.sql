ALTER TABLE public.profiles
  ADD COLUMN IF NOT EXISTS newsletter_consent_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS newsletter_consent_source TEXT,
  ADD COLUMN IF NOT EXISTS newsletter_consent_version TEXT,
  ADD COLUMN IF NOT EXISTS newsletter_unsubscribed_at TIMESTAMPTZ;

UPDATE public.profiles
SET
  newsletter_consent_source = COALESCE(
    newsletter_consent_source,
    'legacy_profile_setting_unknown_date'
  ),
  newsletter_consent_version = COALESCE(newsletter_consent_version, 'legacy-v1'),
  newsletter_unsubscribed_at = NULL
WHERE newsletter_subscribed IS TRUE;

CREATE TABLE IF NOT EXISTS public.email_campaigns (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  campaign_type TEXT NOT NULL CHECK (
    campaign_type IN ('service-update', 'marketing-reactivation')
  ),
  template_version TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'draft' CHECK (
    status IN ('draft', 'ready', 'running', 'completed', 'failed', 'cancelled')
  ),
  created_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  audience_total INTEGER NOT NULL DEFAULT 0 CHECK (audience_total >= 0),
  sent_count INTEGER NOT NULL DEFAULT 0 CHECK (sent_count >= 0),
  failed_count INTEGER NOT NULL DEFAULT 0 CHECK (failed_count >= 0),
  skipped_count INTEGER NOT NULL DEFAULT 0 CHECK (skipped_count >= 0),
  audience_frozen_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  started_at TIMESTAMPTZ,
  completed_at TIMESTAMPTZ,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.email_campaign_deliveries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campaign_id UUID NOT NULL REFERENCES public.email_campaigns(id) ON DELETE CASCADE,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  email_hash TEXT NOT NULL,
  language TEXT NOT NULL DEFAULT 'en',
  batch_number INTEGER NOT NULL CHECK (batch_number >= 1),
  status TEXT NOT NULL DEFAULT 'pending' CHECK (
    status IN ('pending', 'sending', 'sent', 'failed', 'skipped', 'needs_review')
  ),
  attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
  resend_email_id TEXT,
  error_code TEXT,
  claimed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  sent_at TIMESTAMPTZ,
  UNIQUE (campaign_id, user_id)
);

CREATE INDEX IF NOT EXISTS idx_email_campaign_deliveries_claim
  ON public.email_campaign_deliveries (campaign_id, status, batch_number, id);

ALTER TABLE public.email_campaigns ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.email_campaign_deliveries ENABLE ROW LEVEL SECURITY;

