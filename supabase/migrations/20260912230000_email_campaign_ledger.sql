CREATE OR REPLACE FUNCTION public.set_newsletter_preference(
  p_subscribed BOOLEAN
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_user_id UUID := auth.uid();
  v_rows_updated INTEGER;
BEGIN
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Authentication required';
  END IF;

  UPDATE public.profiles
  SET
    newsletter_subscribed = p_subscribed,
    newsletter_consent_at = CASE
      WHEN p_subscribed THEN NOW()
      ELSE newsletter_consent_at
    END,
    newsletter_consent_source = CASE
      WHEN p_subscribed THEN 'profile_settings'
      ELSE newsletter_consent_source
    END,
    newsletter_consent_version = CASE
      WHEN p_subscribed THEN '2026-09-v1'
      ELSE newsletter_consent_version
    END,
    newsletter_unsubscribed_at = CASE
      WHEN p_subscribed THEN NULL
      ELSE COALESCE(newsletter_unsubscribed_at, NOW())
    END,
    updated_at = NOW()
  WHERE id = v_user_id;

  GET DIAGNOSTICS v_rows_updated = ROW_COUNT;
  RETURN v_rows_updated = 1;
END;
$$;

REVOKE ALL ON FUNCTION public.set_newsletter_preference(BOOLEAN) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.set_newsletter_preference(BOOLEAN) TO authenticated;

